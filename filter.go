package zip

import (
	"bytes"
	"encoding/binary"
	"errors"
	"io"
	"sort"
)

// FilterZipStream takes a parsed zip.Reader and a sequential io.Reader (stream)
// representing the exact same underlying zip file data. It evaluates the provided
// filter function for each file. Matched files are streamed efficiently from 'stream'
// directly into 'w', preserving their original compressed byte structures precisely.
// Finally, it hand-constructs and writes a new perfectly compliant Central Directory.
// If no file matches, an empty zip archive is written.
func FilterZipStream(r *Reader, stream io.Reader, w io.Writer, filter func(*File) bool) error {
	var matchedFiles []*File
	for _, f := range r.File {
		if filter(f) {
			matchedFiles = append(matchedFiles, f)
		}
	}

	// Sort files by their physical position in the zip stream
	sort.SliceStable(matchedFiles, func(i, j int) bool {
		return matchedFiles[i].headerOffset < matchedFiles[j].headerOffset
	})

	var streamOffset int64
	var outOffset int64
	newOffsets := make([]int64, len(matchedFiles))
	var lHead [fileHeaderLen]byte
	var nameExtra []byte

	for i, f := range matchedFiles {
		hOffset := f.headerOffset

		// Fast-forward stream to the file's local header
		if hOffset > streamOffset {
			skipped, err := io.CopyN(io.Discard, stream, hOffset-streamOffset)
			streamOffset += skipped
			if err != nil {
				return err
			}
		} else if hOffset < streamOffset {
			return errors.New("zip: cannot stream backwards, offsets must be strictly monotonic")
		}

		newOffsets[i] = outOffset

		// Read Local Header
		if _, err := io.ReadFull(stream, lHead[:]); err != nil {
			return err
		}
		if binary.LittleEndian.Uint32(lHead[:4]) != fileHeaderSignature {
			return ErrFormat
		}
		nameLen := int(binary.LittleEndian.Uint16(lHead[26:28]))
		extraLen := int(binary.LittleEndian.Uint16(lHead[28:30]))

		// Read Name + Extra (at most 128 KiB)
		if cap(nameExtra) < nameLen+extraLen {
			nameExtra = make([]byte, nameLen+extraLen)
		}
		nameExtra = nameExtra[:nameLen+extraLen]
		if _, err := io.ReadFull(stream, nameExtra); err != nil {
			return err
		}
		streamOffset += int64(len(lHead) + len(nameExtra))
		localZip64 := len(removeExtraField(nameExtra[nameLen:], zip64ExtraId)) != extraLen

		if _, err := w.Write(lHead[:]); err != nil {
			return err
		}
		if _, err := w.Write(nameExtra); err != nil {
			return err
		}
		outOffset += int64(len(lHead) + len(nameExtra))

		// Copy Compressed Data
		n, err := io.CopyN(w, stream, int64(f.CompressedSize64))
		streamOffset += n
		outOffset += n
		if err != nil {
			return err
		}

		// Copy Data Descriptor if present
		if f.hasDataDescriptor() {
			var sig [4]byte
			if _, err := io.ReadFull(stream, sig[:]); err != nil {
				return err
			}
			if _, err := w.Write(sig[:]); err != nil {
				return err
			}
			streamOffset += 4
			outOffset += 4

			// Descriptor sizes are 8 bytes each for zip64 entries (an entry
			// with a zip64 local extra, or sizes that need zip64) and 4 bytes
			// otherwise. If the optional signature is absent, the 4 bytes
			// just read were the CRC-32.
			remaining := int64(8)
			if localZip64 || f.isZip64() {
				remaining = 16
			}
			if binary.LittleEndian.Uint32(sig[:]) == dataDescriptorSignature {
				remaining += 4 // CRC-32 still to come
			}

			n, err = io.CopyN(w, stream, remaining)
			streamOffset += n
			outOffset += n
			if err != nil {
				return err
			}
		}
	}

	cdStartOffset := outOffset

	// Write the Central Directory. Extra fields generated by the writer
	// (zip64, xxh3) are dropped from the source extra and regenerated so they
	// describe the new offsets.
	buf := new(bytes.Buffer)
	for i, f := range matchedFiles {
		fh := f.FileHeader
		fh.Extra = removeExtraField(removeExtraField(fh.Extra, zip64ExtraId), xxh3ExtraId)
		// The 32-bit fields may hold 0xFFFFFFFF because the source entry
		// used zip64 for its offset; recompute them from the real sizes.
		fh.CompressedSize = uint32(min(fh.CompressedSize64, uint32max))
		fh.UncompressedSize = uint32(min(fh.UncompressedSize64, uint32max))
		if fh.ae != 0 {
			// The reader replaced Method with the one from the AES extra.
			fh.Method = winzipAesMethod
		}
		if err := writeDirectoryHeader(buf, &header{FileHeader: &fh, offset: uint64(newOffsets[i])}); err != nil {
			return err
		}
	}
	dirSize := uint64(buf.Len())
	if err := writeDirectoryEnd(buf, uint64(len(matchedFiles)), dirSize, uint64(cdStartOffset)); err != nil {
		return err
	}
	_, err := w.Write(buf.Bytes())
	return err
}
